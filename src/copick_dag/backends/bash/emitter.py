"""Render a ``ResolvedPlan`` as a ``copick`` CLI bash script.

Each concrete task becomes one ``copick …`` invocation. Per-op ``vs_style`` controls whether the
voxel spacing is stripped from URIs and passed as ``-vs`` (segop/enclosed) or kept in the URI
(clipseg/cp/mv/rm). ``optional`` tasks are suffixed with ``|| true`` so a missing input does not
abort the pipeline (matching the hand-written scripts, which do not ``set -e``).
"""

from __future__ import annotations

from typing import List, Optional

from copick_dag.plan.concrete import ConcreteTask, ResolvedPlan
from copick_dag.registry import OpSpec, get_op
from copick_dag.registry.introspect import validate_argv
from copick_dag.registry.spec import VS_FLAG
from copick_dag.uris import strip_vs

_SPECIAL = set("*?[]{}()| \t<>$\"'")


def _fmt_num(vs: float) -> str:
    return str(vs)


def _fmt_uri(uri: str, op: OpSpec) -> str:
    return strip_vs(uri) if op.vs_style == VS_FLAG else uri


def task_argv(task: ConcreteTask, config: str) -> List[str]:
    """Build the argv (without a leading ``copick``) for a single task."""
    op = get_op(task.op_id)
    argv: List[str] = list(op.cli_path)

    if op.kind in ("cp", "mv"):
        src = _fmt_uri(_single(task.inputs.get("src")), op)
        dst = _fmt_uri(task.outputs.get("dst"), op)
        argv += [op.object_type_positional, src, dst, "-c", config]
        if task.run is not None:
            argv += ["-r", task.run]
        if task.params.get("overwrite"):
            argv += ["--overwrite"]
        return argv

    if op.kind == "rm":
        uri = _fmt_uri(_single(task.inputs.get("i")), op)
        argv += [op.object_type_positional, uri, "-c", config]
        if task.run is not None:
            argv += ["-r", task.run]
        if task.params.get("force"):
            argv += ["--force"]
        if task.params.get("dry_run"):
            argv += ["--dry-run"]
        return argv

    # generic flag-based op
    argv += ["-c", config]
    if task.run_scope:  # barrier: aggregate over the row's run-set
        for rn in task.run_scope:
            argv += ["-r", rn]
    elif task.run is not None:
        argv += ["-r", task.run]

    for slot in op.inputs:
        val = task.inputs.get(slot.slot)
        if val is None:
            continue
        for u in val if isinstance(val, list) else [val]:
            argv += [slot.flag, _fmt_uri(u, op)]

    for p in op.params:
        if p.name not in task.params:
            continue
        v = task.params[p.name]
        if p.kind == "bool":
            if v:
                argv += [p.flag]
        elif v is not None:
            argv += [p.flag, str(v)]

    if op.vs_style == VS_FLAG and task.voxel_spacing is not None:
        argv += ["-vs", _fmt_num(task.voxel_spacing)]

    for slot in op.outputs:
        if slot.declared or slot.flag is None:
            continue  # edges-only declared output (e.g. split): not emitted
        val = task.outputs.get(slot.slot)
        if val is None:
            continue
        argv += [slot.flag, _fmt_uri(val, op)]

    return argv


def _single(val) -> Optional[str]:
    if isinstance(val, list):
        return val[0] if val else None
    return val


def _quote(arg: str) -> str:
    if arg == "" or any(ch in _SPECIAL for ch in arg):
        return '"' + arg.replace('"', '\\"') + '"'
    return arg


def _render_line(task: ConcreteTask, config: str) -> str:
    argv = task_argv(task, config)
    line = "copick " + " ".join(_quote(a) for a in argv)
    if task.optional:
        line += " || true"
    return line


def render_bash(plan: ResolvedPlan, config_var: str = "CONFIG") -> str:
    """Render the whole plan as a bash script string."""
    cfg = f"${{{config_var}}}"
    lines: List[str] = [
        "#!/usr/bin/env bash",
        "#",
        "# Generated by copick-dag (bash backend). Do not edit by hand.",
        "# Note: intentionally no `set -e` -- optional steps are tolerated via `|| true`,",
        "# mirroring the hand-written copick pipelines.",
        "set -uo pipefail",
        "",
        f'{config_var}="{plan.config}"',
        "",
    ]
    if plan.warnings:
        for w in plan.warnings:
            lines.append(f"# WARNING: {w}")
        lines.append("")

    last_run: Optional[str] = "<none>"
    for task in plan.topo_order():
        run_label = task.run if task.run is not None else "all-runs"
        if run_label != last_run:
            lines.append(f"# ---- run: {run_label} ----")
            last_run = run_label
        lines.append(f"# [{task.node_id}] {task.op_id}")
        lines.append(_render_line(task, cfg))
    lines.append("")
    return "\n".join(lines)


def validate_plan_commands(plan: ResolvedPlan) -> List[str]:
    """Validate every emitted command against Click. Returns a list of error strings (empty == ok).

    Requires ``plan.config`` to point at a real config file (Click validates ``-c`` exists).
    """
    errors: List[str] = []
    for task in plan.tasks:
        argv = task_argv(task, plan.config)
        ok, err = validate_argv(argv)
        if not ok:
            errors.append(f"{task.task_id}: {err}")
    return errors
